"""
@file generate_symbol_index.py
@brief Generates reproducible source declaration links for file-header documentation.
@details Function and variable locations are indexed by the output this script creates.
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
from pathlib import Path

REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
OUTPUT_PATH = REPOSITORY_ROOT / "docs" / "generated" / "symbol-index.md"
FILE_GUIDE_PATH = REPOSITORY_ROOT / "docs" / "source-file-guide.md"
INCLUDED_EXTENSIONS = {".cpp", ".hpp", ".py", ".sh", ".ts", ".mjs", ".js", ".css", ".html"}
PATTERNS = [
    re.compile(r"^\s*(?:class|struct|enum(?:\s+class)?)\s+([A-Za-z_][A-Za-z0-9_]*)"),
    re.compile(r"^\s*(?:def|class)\s+([A-Za-z_][A-Za-z0-9_]*)"),
    re.compile(r"^\s*IMLP_TEST\(([A-Za-z_][A-Za-z0-9_]*)\)"),
    re.compile(r"^\s*(?:function)\(([A-Za-z_][A-Za-z0-9_]*)"),
    re.compile(
        r"^(?:\[\[nodiscard\]\]\s+)?(?:extern\s+\"C\"\s+)?(?:inline\s+)?(?:static\s+)?"
        r"(?:constexpr\s+)?"
        r"[A-Za-z_][A-Za-z0-9_:<>,\s*&]*\s+([A-Za-z_][A-Za-z0-9_:]*)\s*\("
    ),
]


def discover_source_files() -> list[Path]:
    """Return stable, repository-relative source candidates."""
    if __package__:
        from .check_repository import discover_files
    else:
        from check_repository import discover_files

    files = [
        path
        for path in discover_files(REPOSITORY_ROOT)
        if path.suffix in INCLUDED_EXTENSIONS or path.name == "CMakeLists.txt"
    ]
    return sorted(files, key=lambda path: path.relative_to(REPOSITORY_ROOT).as_posix().casefold())


def require_current_parser():
    """Refuse old grammars before producing partial navigation for actual Python3.14 source."""
    try:
        ast.parse("try:\n    pass\nexcept ValueError, TypeError:\n    pass\n")
    except SyntaxError as error:
        raise ValueError("Run this source index with Python3.14 or newer") from error


def python_symbols(source: str) -> list[tuple[str, int]]:
    """Index actual definitions, parameters and assigned names with the interpreter AST."""
    values = set()
    for node in ast.walk(ast.parse(source)):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            values.add(
                (node.lineno, "class" if isinstance(node, ast.ClassDef) else "function", node.name)
            )
        elif isinstance(node, ast.arg):
            values.add((node.lineno, "parameter", node.arg))
        elif isinstance(node, ast.Name) and isinstance(node.ctx, ast.Store):
            values.add((node.lineno, "variable", node.id))
    return [(kind + ": " + name, line) for line, kind, name in sorted(values)]


def browser_symbols(source: str) -> list[tuple[str, int]]:
    """Lexical navigation only; callback bodies/types remain readable in original source."""
    pattern = re.compile(
        r"^\s*(?:export\s+)?(?:async\s+)?(function|class|interface|type|const|let)\s+([A-Za-z_$][\w$]*)"
    )
    return [
        (kind + ": " + name, line)
        for line, value in enumerate(source.splitlines(), 1)
        if (match := pattern.search(value))
        for kind, name in [match.groups()]
    ]


def symbols_for(source: str) -> list[tuple[str, int]]:
    """Extract unique named declarations with exact one-based line numbers."""
    symbols: list[tuple[str, int]] = []
    seen: set[str] = set()
    for line_number, line in enumerate(source.splitlines(), start=1):
        for pattern in PATTERNS:
            match = pattern.search(line)
            if match and match.group(1) not in seen:
                name = match.group(1)
                seen.add(name)
                symbols.append((name, line_number))
                break
    return symbols


def render() -> str:
    """Render the complete Markdown index with repository-relative links."""
    require_current_parser()
    sections: list[str] = []
    for path in discover_source_files():
        relative = path.relative_to(REPOSITORY_ROOT).as_posix()
        source = path.read_text(encoding="utf-8")
        symbols = (
            python_symbols(source)
            if path.suffix == ".py"
            else browser_symbols(source)
            if path.suffix in {".ts", ".mjs", ".js"}
            else symbols_for(source)
        )
        if symbols:
            rows = "\n".join(
                f"- `{name}` — [line {line}](../../{relative}#L{line})" for name, line in symbols
            )
        else:
            rows = "- No named declaration; see the file-level header at line 1."
        sections.append(f"### `{relative}`\n\n{rows}")
    return (
        "<!-- Generated by scripts/generate_symbol_index.py. Do not edit by hand. -->\n\n"
        "# Source symbol index\n\n"
        "This index supplies exact line locations for the classes, functions, tests, and important "
        "declarations summarized by each source file header. Python uses the actual AST; C++ and "
        "TypeScript provide lexical navigation, not complete compiler semantic analysis. "
        "Regenerate it after source changes with "
        "`python scripts/generate_symbol_index.py`; CI rejects stale output.\n\n"
        + "\n\n".join(sections)
        + "\n"
    )


def render_file_guide() -> str:
    """List actual public deliverables with a concise purpose, never private output."""
    if __package__:
        from .check_repository import discover_files
    else:
        from check_repository import discover_files
    rows = []
    for path in discover_files(REPOSITORY_ROOT):
        relative = path.relative_to(REPOSITORY_ROOT).as_posix()
        if path.suffix == ".docx":
            purpose = (
                "Historical reviewed Word edition; its publication manifest retains "
                "its own source scope."
            )
        elif relative.startswith("licenses/"):
            purpose = (
                "Original upstream component terms retained verbatim; "
                "not authored application code."
            )
        elif relative.startswith(".github/workflows/"):
            purpose = (
                "Pinned workflow for "
                + path.stem.replace("-", " ")
                + "; see current validation report."
            )
        elif path.suffix in INCLUDED_EXTENSIONS or path.name == "CMakeLists.txt":
            opening = path.read_text(encoding="utf-8").splitlines()[:10]
            brief = next(
                (line.split("@brief", 1)[1].strip(" */") for line in opening if "@brief" in line),
                "",
            )
            purpose = (
                brief or "Authored source with definitions and variables in the exact symbol index."
            )
        elif relative.startswith("requirements"):
            purpose = (
                "Exact dependency input/hash lock for isolated runtime, test or packaging tools."
            )
        elif path.suffix == ".md":
            purpose = next(
                (
                    line.lstrip("# ")
                    for line in path.read_text(encoding="utf-8").splitlines()
                    if line.startswith("# ")
                ),
                "Documentation and dated evidence.",
            )
        else:
            purpose = (
                "Product configuration, dependency identity or repository publication metadata."
            )
        rows.append(f"| [`{relative}`](../{relative}) | {purpose.replace('|', '/')} |")
    return (
        "# Complete maintained file guide\n\nGenerated from Git tracked and proposed public files; "
        "ignored private runtimes are outside publication scope. Exact definitions and Python "
        "parameters/variables are in the [symbol index](generated/symbol-index.md).\n\n"
        "| File | Purpose |\n| --- | --- |\n" + "\n".join(rows) + "\n"
    )


def main() -> int:
    """Write the index or compare it byte-for-byte when --check is supplied."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    generated = render()
    file_guide = render_file_guide()
    if arguments.check:
        existing = OUTPUT_PATH.read_text(encoding="utf-8") if OUTPUT_PATH.exists() else ""
        if existing != generated:
            print("docs/generated/symbol-index.md is stale", file=sys.stderr)
            return 1
        if (
            not FILE_GUIDE_PATH.is_file()
            or FILE_GUIDE_PATH.read_text(encoding="utf-8") != file_guide
        ):
            print("docs/source-file-guide.md is stale", file=sys.stderr)
            return 1
        return 0
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(generated, encoding="utf-8")
    FILE_GUIDE_PATH.write_text(file_guide, encoding="utf-8")
    print(f"Indexed {len(discover_source_files())} source files.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
